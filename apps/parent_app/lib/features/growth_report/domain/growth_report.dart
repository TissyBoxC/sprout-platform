/// Reporting windows a growth report can cover.
enum GrowthReportPeriod {
  weekly('weekly', '周报'),
  monthly('monthly', '月报');

  const GrowthReportPeriod(this.apiValue, this.label);

  final String apiValue;
  final String label;

  static GrowthReportPeriod fromApiValue(String value) {
    for (final period in GrowthReportPeriod.values) {
      if (period.apiValue == value) {
        return period;
      }
    }
    return GrowthReportPeriod.weekly;
  }
}

/// Practice counts for one window.
class PracticeTotals {
  const PracticeTotals({
    required this.attempts,
    required this.passed,
    required this.averageScore,
    required this.accuracy,
  });

  const PracticeTotals.empty()
    : attempts = 0,
      passed = 0,
      averageScore = 0,
      accuracy = 0;

  final int attempts;
  final int passed;
  final double averageScore;

  /// Pass rate in percent, computed by the platform so the app and the console
  /// cannot disagree about rounding.
  final double accuracy;

  bool get isEmpty => attempts == 0;

  factory PracticeTotals.fromJson(Map<String, dynamic> json) {
    return PracticeTotals(
      attempts: _intValue(json['attempts']),
      passed: _intValue(json['passed']),
      averageScore: _doubleValue(json['average_score']),
      accuracy: _doubleValue(json['accuracy']),
    );
  }
}

/// Device activity for one window.
class UsageTotals {
  const UsageTotals({
    required this.activeSeconds,
    required this.conversationCount,
    required this.conversationSeconds,
  });

  const UsageTotals.empty()
    : activeSeconds = 0,
      conversationCount = 0,
      conversationSeconds = 0;

  final int activeSeconds;
  final int conversationCount;
  final int conversationSeconds;

  /// Whole minutes, because a report never needs second precision.
  int get activeMinutes => activeSeconds ~/ 60;

  factory UsageTotals.fromJson(Map<String, dynamic> json) {
    return UsageTotals(
      activeSeconds: _intValue(json['active_seconds']),
      conversationCount: _intValue(json['conversation_count']),
      conversationSeconds: _intValue(json['conversation_seconds']),
    );
  }
}

/// Guardian-authored entry counts for one window.
class ReportCounts {
  const ReportCounts({required this.growthRecords, required this.memories});

  const ReportCounts.empty() : growthRecords = 0, memories = 0;

  final int growthRecords;

  /// Number of memories added. The report never carries their content.
  final int memories;

  factory ReportCounts.fromJson(Map<String, dynamic> json) {
    return ReportCounts(
      growthRecords: _intValue(json['growth_records']),
      memories: _intValue(json['memories']),
    );
  }
}

/// One stored growth report.
///
/// The report holds aggregates only: no conversation text, no memory value and
/// no media. A summary sentence is generated by the platform so the wording
/// stays consistent between the app and the console.
class GrowthReport {
  const GrowthReport({
    required this.id,
    required this.childId,
    required this.period,
    required this.periodStart,
    required this.periodEnd,
    required this.practice,
    required this.previousPractice,
    required this.usage,
    required this.counts,
    required this.practiceDelta,
    required this.accuracyDelta,
    required this.activeSecondsDelta,
    required this.accuracyPhrase,
    required this.summary,
    required this.generatedAt,
  });

  final String id;
  final String childId;
  final GrowthReportPeriod period;
  final DateTime? periodStart;

  /// Exclusive end of the window; the report covers [periodStart, periodEnd).
  final DateTime? periodEnd;
  final PracticeTotals practice;
  final PracticeTotals previousPractice;
  final UsageTotals usage;
  final ReportCounts counts;
  final int practiceDelta;
  final double accuracyDelta;
  final int activeSecondsDelta;
  final String accuracyPhrase;
  final String summary;
  final DateTime? generatedAt;

  /// A report with no practice and no usage is still a real report; the screen
  /// says the period was quiet instead of hiding it.
  bool get isQuiet =>
      practice.isEmpty && usage.activeSeconds == 0 && counts.growthRecords == 0;

  /// Human-readable window, such as "10月19日 - 10月25日".
  String get periodLabel {
    final start = periodStart;
    final end = periodEnd;
    if (start == null) {
      return '';
    }
    final lastDay = end?.subtract(const Duration(days: 1));
    if (lastDay == null) {
      return '${start.month}月${start.day}日';
    }
    return '${start.month}月${start.day}日 - ${lastDay.month}月${lastDay.day}日';
  }

  factory GrowthReport.fromJson(Map<String, dynamic> json) {
    final metrics = json['metrics'];
    final metricsMap = metrics is Map ? metrics.cast<String, dynamic>() : null;
    final deltas = metricsMap?['deltas'];
    final deltasMap = deltas is Map ? deltas.cast<String, dynamic>() : null;
    return GrowthReport(
      id: _stringValue(json['id']),
      childId: _stringValue(json['child_id']),
      period: GrowthReportPeriod.fromApiValue(
        _stringValue(json['period_type']),
      ),
      periodStart: DateTime.tryParse(_stringValue(json['period_start'])),
      periodEnd: DateTime.tryParse(_stringValue(json['period_end'])),
      practice: _totals(metricsMap?['practice']),
      previousPractice: _totals(metricsMap?['previous_practice']),
      usage: _usage(metricsMap?['usage']),
      counts: _counts(metricsMap?['counts']),
      practiceDelta: _intValue(deltasMap?['practice']),
      accuracyDelta: _doubleValue(deltasMap?['accuracy']),
      activeSecondsDelta: _intValue(deltasMap?['active_seconds']),
      accuracyPhrase: _stringValue(metricsMap?['accuracy_phrase']),
      summary: _stringValue(json['summary']),
      generatedAt: DateTime.tryParse(_stringValue(json['generated_at'])),
    );
  }
}

PracticeTotals _totals(Object? value) {
  if (value is Map) {
    return PracticeTotals.fromJson(value.cast<String, dynamic>());
  }
  return const PracticeTotals.empty();
}

UsageTotals _usage(Object? value) {
  if (value is Map) {
    return UsageTotals.fromJson(value.cast<String, dynamic>());
  }
  return const UsageTotals.empty();
}

ReportCounts _counts(Object? value) {
  if (value is Map) {
    return ReportCounts.fromJson(value.cast<String, dynamic>());
  }
  return const ReportCounts.empty();
}

String _stringValue(Object? value) => value is String ? value : '';

int _intValue(Object? value) {
  if (value is int) {
    return value;
  }
  if (value is num) {
    return value.toInt();
  }
  return 0;
}

double _doubleValue(Object? value) {
  if (value is num) {
    return value.toDouble();
  }
  return 0;
}
