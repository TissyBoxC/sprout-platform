/// Resolves the signed-in family id before the report API can address it.
final growthReportFamilyIdProvider = FutureProvider<String>((ref) async {
  final family = await ref.watch(familyControllerProvider.future);
  return family.capability.familyId;
});

final growthReportApiProvider = Provider<GrowthReportApi?>((ref) {
  final familyId = ref.watch(growthReportFamilyIdProvider).value;
  if (familyId == null || familyId.isEmpty) {
    // Nothing may be requested before the family is known: an empty family id
    // would reach the platform as a permission error rather than a load state.
    return null;
  }
  return HttpGrowthReportApi(ref.watch(apiClientProvider), familyId);
});

/// Everything the growth report screen renders for one child.
class GrowthReportState {
  const GrowthReportState({
    required this.childId,
    required this.reports,
    this.filter,
  });

  const GrowthReportState.initial()
    : childId = '',
      reports = const <GrowthReport>[],
      filter = null;

  final String childId;
  final List<GrowthReport> reports;

  /// When set, only this period is shown.
  final GrowthReportPeriod? filter;

  bool get isEmpty => reports.isEmpty;

  /// The filter the screen starts on:月度 once there is one, otherwise weekly.
  List<GrowthReport> get visibleReports {
    final selected = filter;
    if (selected == null) {
      return reports;
    }
    return reports
        .where((report) => report.period == selected)
        .toList(growable: false);
  }
}

/// Loads one child's growth reports.
///
/// Reports are generated by the platform on a schedule, so the newest one may
/// cover a period that ended days ago. The screen says which window a report
/// covers rather than implying it is live.
class GrowthReportController extends AsyncNotifier<GrowthReportState> {
  int _requestGeneration = 0;

  @override
  Future<GrowthReportState> build() async {
    return const GrowthReportState.initial();
  }

  /// Loads a child's reports.
  Future<void> load(String childId) async {
    final generation = ++_requestGeneration;
    state = const AsyncValue<GrowthReportState>.loading();
    final next = await AsyncValue.guard(() async {
      final api = await _api();
      final reports = await api.fetchReports(childId);
      return GrowthReportState(childId: childId, reports: reports);
    });
    if (generation != _requestGeneration) {
      return;
    }
    state = next;
  }

  /// Narrows the list to one period without refetching.
  void setFilter(GrowthReportPeriod? filter) {
    final current = state.value;
    if (current == null) {
      return;
    }
    state = AsyncValue<GrowthReportState>.data(
      GrowthReportState(
        childId: current.childId,
        reports: current.reports,
        filter: filter,
      ),
    );
  }

  Future<GrowthReportApi> _api() async {
    await ref.read(growthReportFamilyIdProvider.future);
    final api = ref.read(growthReportApiProvider);
    if (api == null) {
      throw StateError('growth report api is not ready');
    }
    return api;
  }
}

final growthReportControllerProvider =
    AsyncNotifierProvider<GrowthReportController, GrowthReportState>(
      GrowthReportController.new,
    );
